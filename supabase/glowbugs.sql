-- Collect a finished row's diamond. The server checks its own results: every Glowbug of that kind rescued
-- (a level it naps on solved with three stars), and the row not collected before.
create or replace function public.claim_glowbug_row(p_kind text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := public._require_user();
  v_profile public.profiles;
  v_colors integer;
  v_rescued integer;
begin
  select count(distinct glowbug_id) into v_colors from public.glowbug_levels where kind = p_kind;
  if v_colors = 0 then
    raise exception using message = 'That Glowbug row doesn’t exist.';
  end if;
  select count(distinct g.glowbug_id) into v_rescued
    from public.glowbug_levels g
    join public.progress p on p.level_id = g.level_id and p.user_id = v_user and p.stars = 3
    where g.kind = p_kind;
  if v_rescued < v_colors then
    raise exception using message = 'Rescue every Glowbug in this row first.';
  end if;
  select * into v_profile from public.profiles where id = v_user for update;
  if p_kind = any (v_profile.glowbug_rows_claimed) then
    raise exception using message = 'You already collected this row.';
  end if;
  update public.profiles set
    diamonds = diamonds + 1,
    glowbug_rows_claimed = array_append(glowbug_rows_claimed, p_kind)
  where id = v_user;
  return public._economy_state(v_user);
end;
$$;
